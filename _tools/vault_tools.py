"""Vault maintenance for 'niceforwh vault' (read-mostly).

  python -I vault_tools.py index <vault>   -> writes INDEX.md and INDEX_SLIM.md (own notes only, nested fwjelaa vault excluded)
  python -I vault_tools.py links <vault>   -> prints wikilinks in own notes that resolve to no file (exit 1 if any)
  python -I vault_tools.py names <vault>   -> prints own note names that collide with notes inside the nested fwjelaa vault

Own notes = every .md outside _originali/ and outside the intact projects listed in INTACT.
"""
import os, re, sys

INTACT = ('_originali/', '07 Tools and Pipelines/', '08 Knowledge/fwjelaa-vault/', '08 Knowledge/roblox-ai/', '.obsidian/')
NESTED = '08 Knowledge/fwjelaa-vault/'
LINK = re.compile(r'(!?)\[\[([^\]|#^]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]')


def walk(root):
    for dp, dns, fns in os.walk(root):
        for fn in fns:
            p = os.path.join(dp, fn)
            yield os.path.relpath(p, root).replace(os.sep, '/')


def own(rel):
    return not rel.startswith(INTACT)


def frontmatter(text):
    m = re.match(r'---\n(.*?)\n---\n', text, re.S)
    tags = []
    if m:
        t = re.search(r'tags:\s*\[(.*?)\]', m.group(1))
        if t:
            tags = [x.strip() for x in t.group(1).split(',') if x.strip()]
        text = text[m.end():]
    return tags, text


def first_sentence(body):
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(('#', '>', '|', '-', '!', '<', '```', '*')):
            continue
        s = re.sub(r'\[\[([^\]|]+\|)?([^\]]+)\]\]', r'\2', s)
        m = re.match(r'(.+?[.!?])(\s|$)', s)
        s = m.group(1) if m else s
        return s if len(s) < 140 else s[:137] + '...'
    return ''


def index(root):
    notes = sorted(r for r in walk(root) if r.endswith('.md') and own(r)
                   and os.path.basename(r) not in ('INDEX.md', 'INDEX_SLIM.md'))
    sections = {}
    for r in notes:
        top = r.split('/')[0] if '/' in r else '(root)'
        text = open(os.path.join(root, r), encoding='utf-8', errors='replace').read()
        tags, body = frontmatter(text)
        tok = max(1, round(len(text) / 4 / 100) / 10)
        sections.setdefault(top, []).append((os.path.splitext(os.path.basename(r))[0], r, ', '.join(tags), tok, first_sentence(body)))
    head = ('# niceforwh vault Index\n\nMachine-friendly index of every own note: `title | path | tags | ~tokens | first sentence`. '
            'Grep it for a topic or tag, then open only the notes you need. Generated by `_tools/vault_tools.py index` '
            '(do not edit by hand); `INDEX_SLIM.md` is the same without first sentences, [[ROUTER]] is the keyword map. '
            'The nested fwjelaa vault has its own index: [[08 Knowledge/fwjelaa-vault/fwjelaa vault/INDEX|fwjelaa INDEX]].\n')
    full, slim = [head], [head.replace('niceforwh vault Index', 'niceforwh vault Index (slim)')]
    for sec in sorted(sections):
        full.append(f'\n## {sec}\n')
        slim.append(f'\n## {sec}\n')
        for t, r, tg, tok, fs in sections[sec]:
            full.append(f'- {t} | {r} | {tg} | ~{tok}k tok | {fs}')
            slim.append(f'- {t} | {r} | {tg} | ~{tok}k tok')
    open(os.path.join(root, 'INDEX.md'), 'w', encoding='utf-8').write('\n'.join(full) + '\n')
    open(os.path.join(root, 'INDEX_SLIM.md'), 'w', encoding='utf-8').write('\n'.join(slim) + '\n')
    print(len(notes), 'notes indexed')


def all_targets(root):
    names, paths = set(), set()
    for r in walk(root):
        if r.startswith('_originali/'):
            continue
        base = os.path.basename(r)
        stem = os.path.splitext(base)[0] if base.endswith('.md') else base
        names.add(stem.lower())
        names.add(base.lower())
        paths.add(r.lower())
        if r.endswith('.md'):
            paths.add(r[:-3].lower())
    return names, paths


def links(root):
    names, paths = all_targets(root)
    bad = 0
    for r in walk(root):
        if not (r.endswith(('.md', '.canvas')) and own(r)):
            continue
        text = open(os.path.join(root, r), encoding='utf-8', errors='replace').read()
        cands = [m.group(2).strip() for m in LINK.finditer(text)]
        if r.endswith('.canvas'):
            cands += re.findall(r'"file"\s*:\s*"([^"]+)"', text)
        for tgt in cands:
            t = tgt.replace('\\', '/').strip().lower()
            if t in paths or t in names or os.path.basename(t) in names:
                continue
            print(f'BROKEN {r}: [[{tgt}]]')
            bad += 1
    print(bad, 'broken links')
    return bad


def names_cmd(root):
    mine, nested = {}, {}
    for r in walk(root):
        if not r.endswith('.md'):
            continue
        stem = os.path.splitext(os.path.basename(r))[0].lower()
        if r.startswith(NESTED):
            nested.setdefault(stem, r)
        elif own(r):
            mine.setdefault(stem, r)
    hits = sorted(set(mine) & set(nested))
    for h in hits:
        print(f'COLLIDE {mine[h]}  <->  {nested[h]}')
    print(len(hits), 'collisions')


if __name__ == '__main__':
    cmd, root = sys.argv[1], sys.argv[2]
    if cmd == 'index':
        index(root)
    elif cmd == 'links':
        sys.exit(1 if links(root) else 0)
    elif cmd == 'names':
        names_cmd(root)
